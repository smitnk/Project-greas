#!/usr/bin/env python3
"""L8: packs the generated GLES shaders (DIR/<info>.vert.glsl, .frag.glsl) into DIR/pg_gles_shaders.inc,
a C++ table {info name, vertex source, fragment source} the GLES runtime compiles from. Pure packaging:
the sources are copied byte for byte into raw string literals.

  python3 -I tools/gles_shaders/embed.py DIR info...
"""
import sys
from pathlib import Path

DELIM = "PGGLSL"


def raw(text):
    if ")" + DELIM + '"' in text:
        raise SystemExit("shader source contains the raw-string delimiter")
    # MSVC-safe chunking is not needed (GCC / Clang): one literal per stage.
    return 'R"' + DELIM + "(" + text + ")" + DELIM + '"'


def main():
    d = Path(sys.argv[1])
    rows = []
    for info in sys.argv[2:]:
        v = (d / f"{info}.vert.glsl").read_text()
        f = (d / f"{info}.frag.glsl").read_text()
        rows.append(f'    {{"{info}",\n     {raw(v)},\n     {raw(f)}}},')
    out = (
        "/* GENERATED by tools/gles_shaders/embed.py from the shaders in this directory. Do not edit. */\n"
        "struct PGGlesShaderSource {\n  const char *info;\n  const char *vert;\n  const char *frag;\n};\n"
        "static const PGGlesShaderSource pg_gles_shader_sources[] = {\n" + "\n".join(rows) + "\n};\n"
    )
    (d / "pg_gles_shaders.inc").write_text(out)


if __name__ == "__main__":
    main()
