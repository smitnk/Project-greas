#!/usr/bin/env python3
"""L4: turns the pg_rna_dump output (Blender 3.6.23's own RNA definitions for the Grease Pencil
structs, run through rna_define.c) into native/blender_gp/rna/project_grease_rna_gen.c.

  python3 -I tools/rna_ranges/gen_rna_table.py DUMP.tsv          write the table
  python3 -I tools/rna_ranges/gen_rna_table.py DUMP.tsv --check  fail if the committed table differs

Nothing is computed: every number is copied from the dump. Structs outside Project Grease's 2D
scope (Shrinkwrap, Armature: 3D mesh/armature evaluation) are left out by name.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "native/blender_gp/rna/project_grease_rna_gen.c"
EXCLUDED = {"ShrinkwrapGpencilModifier", "ArmatureGpencilModifier"}  # 2D scope decision
# PropertyType (RNA_types.h): PROP_BOOLEAN 0, PROP_INT 1, PROP_FLOAT 2, PROP_STRING 3, PROP_ENUM 4,
# PROP_POINTER 5, PROP_COLLECTION 6.


def c_str(s):
    return "NULL" if s in ("-", "") else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_num(s):
    v = float(s)
    if v == float("inf") or v >= 3.4028234e38:
        return "FLT_MAX"
    if v == float("-inf") or v <= -3.4028234e38:
        return "-FLT_MAX"
    if v == int(v) and abs(v) >= 2147483647:
        return "INT_MAX" if v > 0 else "INT_MIN"
    return s


def main():
    dump, check = sys.argv[1], "--check" in sys.argv[2:]
    rows, enums = [], []
    for line in Path(dump).read_text().splitlines():
        f = line.split("\t")
        srna, prop, dna, ptype, subtype, alen = f[:6]
        if srna in EXCLUDED:
            continue
        kv = {}
        for x in f[6:]:
            k, _, v = x.partition("=")
            kv[k] = v if _ else "1"
        dstruct, _, dfield = dna.partition(".")
        hmin = hmax = smin = smax = step = "0"
        prec, items, bit = "0", "NULL", "0"
        ntot = 0
        if "hard" in kv:
            hmin, hmax = kv["hard"].split("..")
            smin, smax = kv["soft"].split("..")
            step = kv["step"]
            prec = kv.get("precision", "0")
        if "items" in kv and kv["items"]:
            vals = [it.split(":")[0] for it in kv["items"].split(",")]
            name = f"items_{len(enums)}"
            enums.append(f"static const int {name}[] = {{{', '.join(vals)}}};")
            items, ntot = name, len(vals)
        if "bit" in kv:
            bit = kv["bit"]
        rows.append(
            f'  {{{c_str(srna)}, {c_str(prop)}, {c_str(dstruct)}, {c_str(dfield)}, {ptype}, {subtype}, {alen}, '
            f'{c_num(hmin)}, {c_num(hmax)}, {c_num(smin)}, {c_num(smax)}, {step}, {prec}, {items}, {ntot}, '
            f'{bit}LL, {1 if "negative" in kv else 0}, '
            f'{c_str(kv.get("range_fn", "-"))}, {c_str(kv.get("set_fn", "-"))}, {c_str(kv.get("item_fn", "-"))}}},'
        )
    text = (
        "/* GENERATED by tools/rna_ranges/gen_rna_table.py from Blender 3.6.23's own RNA definitions\n"
        " * (rna_gpencil_legacy.c, rna_gpencil_legacy_modifier.c, rna_shader_fx.c run through rna_define.c\n"
        " * by tools/rna_ranges/pg_rna_dump.c). Do not edit; CI regenerates and compares it.\n"
        " * Excluded (2D scope): " + ", ".join(sorted(EXCLUDED)) + ". */\n"
        "#include <float.h>\n#include <limits.h>\n#include <stddef.h>\n\n"
        '#include "project_grease_rna.h"\n\n'
        + "\n".join(enums)
        + "\n\nconst PGRnaProperty pg_rna_properties[] = {\n"
        + "\n".join(rows)
        + "\n};\nconst int pg_rna_properties_len = (int)(sizeof(pg_rna_properties) / sizeof(pg_rna_properties[0]));\n"
    )
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"ERROR: {OUT.relative_to(ROOT)} is not what Blender 3.6.23's RNA produces; regenerate it",
                  file=sys.stderr)
            return 1
        print(f"RNA table is up to date ({len(rows)} properties)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} properties)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
